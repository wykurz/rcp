    fn elapsed_timeline_write_failures_are_returned() {
        let file = std::fs::OpenOptions::new()
            .write(true)
            .open("/dev/full")
            .unwrap();
        let (layer, mut guard) = TimingLayer::new("unwritable".into(), None, Some(file));
        let subscriber =
            tracing_subscriber::registry().with(layer.with_filter(timing_filter(false)));
        tracing::subscriber::with_default(subscriber, || crate::timing_scope!("scope").finish());
        assert!(guard.finish().is_err());
    }
