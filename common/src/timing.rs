    #[test]
    fn delayed_scope_registration_cannot_reuse_an_overlapping_lane() {
        let file = tempfile::NamedTempFile::new().unwrap();
        let (_, guard) = TimingLayer::new("timeline".into(), None, Some(file.reopen().unwrap()));
        let mut state = guard.state.lock().unwrap();
        let start = state.epoch;
        let first_lane = state.allocate_lane(start);
        state.record(
            ActiveScope {
                name: "first",
                start,
                lane: first_lane,
            },
            true,
            start + std::time::Duration::from_secs(2),
        );
        let overlapping_lane = state.allocate_lane(start + std::time::Duration::from_secs(1));
        assert_ne!(overlapping_lane, first_lane);
        let later_lane = state.allocate_lane(start + std::time::Duration::from_secs(3));
        assert_eq!(later_lane, first_lane);
    }

